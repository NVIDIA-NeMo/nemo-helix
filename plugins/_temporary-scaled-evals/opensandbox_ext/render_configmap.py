"""Write the ConfigMap that ships the OpenSandbox server extension.

    uv run python plugins/_temporary-scaled-evals/opensandbox_ext/render_configmap.py

The server loads the extension from plain source files mounted from this ConfigMap, so the
committed manifest must contain exactly the current sources. A unit test fails when it is
out of date; rerun this script after changing any file in ``SOURCES``.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]

# Every module the server needs, mounted side by side in one directory on its PYTHONPATH.
SOURCES = ("nemo_ext_spec.py", "nemo_ext_pod.py", "nemo_opensandbox_ext.py", "sitecustomize.py")
NAME = "nemo-opensandbox-ext"
OUTPUT = REPO / "k8s/helm/examples/opensandbox/nemo-opensandbox-ext.yaml"

HEADER = """\
# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
# SPDX-License-Identifier: Apache-2.0

# GENERATED by plugins/_temporary-scaled-evals/opensandbox_ext/render_configmap.py. Do not edit.
#
# NeMo services extension for the OpenSandbox server: lets a sandbox run a task's Docker
# Compose services as extra containers in its pod. Apply in the server namespace, then
# restart the server (see README.md, "Compose services").
"""


def render() -> str:
    """The ConfigMap manifest: one data key per source file, plus an annotation with their combined hash.

    Written line by line rather than with a YAML library, so the sources appear verbatim as
    readable block scalars and the output is identical on every run.
    """
    files = {name: (HERE / name).read_text() for name in SOURCES}

    # Tells which extension sources a deployed ConfigMap was rendered from.
    digest = hashlib.sha256("".join(f"{n}\0{files[n]}" for n in SOURCES).encode()).hexdigest()[:12]

    lines = [
        HEADER,
        "apiVersion: v1",
        "kind: ConfigMap",
        "metadata:",
        f"  name: {NAME}",
        "  labels:",
        "    app.kubernetes.io/name: nemo-opensandbox-ext",
        "  annotations:",
        f'    nemo.nvidia.com/source-sha256: "{digest}"',
        "data:",
    ]

    # YAML block scalars, indented under their key; blank lines stay empty.
    for name in SOURCES:
        lines.append(f"  {name}: |")
        lines.extend(f"    {line}" if line else "" for line in files[name].splitlines())
    return "\n".join(lines) + "\n"


def main() -> int:
    """Write the manifest to ``OUTPUT``."""
    OUTPUT.write_text(render())
    print(f"wrote {OUTPUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
