"""SDK resources for Kubernetes taskset runs, mounted as ``Evaluator.taskset_runs``.

A taskset run evaluates a pinned taskset revision as one Jobs Service Job per task. These resources submit
runs, read them, cancel them, walk their tasks with the tasks' names in the pinned taskset, and join each
completed task with its result record.

Retries: ``submit`` always uses :data:`SUBMIT_RETRY`. It never resends a body the server may already have,
and the server's ``x-should-retry`` decides what else is resent. Every other method follows the client's own
retry policy.
"""

from __future__ import annotations

import builtins
from collections.abc import AsyncIterator, Iterator
from uuid import uuid4

import httpx
from nemo_evals.api.schemas import AgentEvalResult, Taskset
from nemo_evals.api.taskset_run_schemas import (
    TasksetRunInput,
    TasksetRunStatus,
    TasksetRunSubmitResponse,
    TasksetRunTask,
)
from nemo_evals.sdk import taskset_run_endpoints as endpoints
from nemo_evals.sdk.result_resources import AsyncEvaluatorAgentEvalResultsResource, EvaluatorAgentEvalResultsResource
from nemo_evals.sdk.taskset_resources import AsyncEvaluatorTasksetsResource, EvaluatorTasksetsResource
from nemo_evals.taskset_runs.entities import MemberPhase
from nemo_helix_plugin.client.errors import NemoClientError, NemoHTTPError, NotFoundError, PermissionDeniedError
from nemo_helix_plugin.client.types import RetryPolicy
from nemo_helix_plugin.evals.client import AsyncEvaluatorClient, EvaluatorClient
from nemo_helix_plugin.schema import Page
from pydantic import BaseModel, ConfigDict

SUBMIT_RETRY = RetryPolicy(
    # 2, 4, 8, 16 s (about 30 s): a submit can follow minutes of image builds, so ride out an API pod restart.
    max_retries=4,
    backoff_base=2.0,
    # A gateway 502/504 without x-should-retry may come after the server took the body: not resent.
    retryable_status_codes=(429, 503),
    respect_retry_decision_headers=True,
    respect_retry_after_headers=True,
    resend_after_body_sent=False,
)
"""Submit's retry policy, whatever the client's: resend only what the server never got or asked for again."""

SUBMIT_TIMEOUT = httpx.Timeout(300.0, connect=10.0)
"""Submit answers once the run is accepted, which can take minutes; a connect is quick or not happening."""

_TASKS_PAGE_SIZE = 1000
_TASKSET_CACHE_SIZE = 64

_TasksetKey = tuple[str, str, str]


class NamedTask(BaseModel):
    """One task of a run, with its name in the pinned taskset."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    index: int
    """The task's index in the pinned taskset."""
    name: str
    """The task's name in the pinned taskset; the member name (``task-<i>``) when the taskset can't be read."""
    task: TasksetRunTask | None = None
    """The task's ``/tasks`` row; None until the run controller creates it."""


class TaskResult(NamedTask):
    """One task of a run with its result record."""

    result: AgentEvalResult | None = None
    """Set when the task's Job completed and wrote a result record."""


class TasksetRunResults(BaseModel):
    """A run, each of its tasks with its result, and the run's merged record."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    run: TasksetRunStatus
    tasks: list[TaskResult]
    result: AgentEvalResult | None = None
    """The run's merged record; set once ``run.result_state`` is ``ready``."""


class TasksetRunSubmitError(NemoClientError):
    """Every submit failure. The typed client error is ``__cause__``.

    Attributes:
        idempotency_key: The key this submit used, generated by the SDK when the request had none. Resubmitting
            with it replays the run instead of starting a second one.
        status_code: The error status the server returned; None for a transport failure or a 2xx whose body
            didn't parse.
        request_id: The response's ``x-request-id``, when there was a response.
    """

    def __init__(self, cause: NemoClientError, idempotency_key: str) -> None:
        self.idempotency_key = idempotency_key
        self.status_code: int | None = cause.status_code if isinstance(cause, NemoHTTPError) else None
        response: httpx.Response | None = getattr(cause, "http_response", None)
        self.request_id: str | None = response.headers.get("x-request-id") if response is not None else None
        suffix = f"; request_id={self.request_id}" if self.request_id else ""
        super().__init__(f"{cause}; this submit used idempotency_key={idempotency_key}{suffix}")


# --- Pure helpers shared by the sync and async resources --------------------------------------------------


def _wire_request(request: TasksetRunInput) -> TasksetRunInput:
    """``request`` with an idempotency key, every non-None field marked as set.

    Typed endpoints send ``exclude_unset``: a default left unset, such as a Harbor target's ``kind``, would be
    dropped, and the server would read the target as another kind. Re-validating the ``exclude_none`` dump marks
    every field set, so the body sent is that dump.
    """
    keyed = request if request.idempotency_key else request.model_copy(update={"idempotency_key": uuid4().hex})
    return TasksetRunInput.model_validate(keyed.model_dump(mode="json", exclude_none=True))


def _split_ref(ref: str) -> _TasksetKey:
    head, _, digest = ref.partition("#")
    workspace, _, name = head.partition("/")
    return workspace, name, digest


def _names_by_index(taskset: Taskset | None) -> dict[int, str]:
    """Each task's name by its index in ``taskset``; empty when the taskset couldn't be read."""
    if taskset is None:
        return {}
    return {index: _split_ref(member.root)[1] for index, member in enumerate(taskset.tasks)}


def _named_tasks(names: dict[int, str], rows: builtins.list[TasksetRunTask]) -> builtins.list[NamedTask]:
    """One entry per taskset index, plus any row whose index the taskset lacks, in index order."""
    by_index = {row.task_index: row for row in rows}
    return [
        NamedTask(index=i, name=names.get(i) or by_index[i].task, task=by_index.get(i))
        for i in sorted(names.keys() | by_index.keys())
    ]


def _completed_job(named: NamedTask) -> str | None:
    """The task's Job name once that Job completed; None before then, or when the task has no row."""
    row = named.task
    if row is None or row.job_status != "completed":
        return None
    return row.job


def _with_result(named: NamedTask, result: AgentEvalResult | None) -> TaskResult:
    return TaskResult(index=named.index, name=named.name, task=named.task, result=result)


def _remember(cache: dict[_TasksetKey, Taskset], key: _TasksetKey, taskset: Taskset) -> None:
    """Cache a pinned revision, evicting the oldest past the cap. A pinned revision never changes."""
    cache[key] = taskset
    while len(cache) > _TASKSET_CACHE_SIZE:
        del cache[next(iter(cache))]


def _last_page(page: Page[TasksetRunTask], number: int) -> bool:
    return not page.data or page.pagination is None or number >= page.pagination.total_pages


