class EvaluatorTasksetRunsResource:
    """Sync resource mounted as ``Evaluator.taskset_runs``.

    Retries: ``submit`` always uses its own :data:`SUBMIT_RETRY` (no resend after the body was sent; the
    server's ``x-should-retry`` decides). Every other method follows the client's retry policy.
    """

    def __init__(self, client: EvaluatorClient) -> None:
        self._client = client
        self._tasksets = EvaluatorTasksetsResource(client)
        self._results = EvaluatorAgentEvalResultsResource(client)
        self._taskset_cache: dict[_TasksetKey, Taskset] = {}

    def submit(self, request: TasksetRunInput, *, workspace: str | None = None) -> TasksetRunSubmitResponse:
        """Submit a run; a resubmit with the same ``idempotency_key`` returns the same run.

        Raises ``TasksetRunSubmitError`` for every failure. It carries ``idempotency_key`` (generated here if the
        request had none) and ``status_code`` (the error status; None for a transport failure or an unparseable
        2xx), with the typed client error as ``__cause__``.

        Cancellation (``KeyboardInterrupt``) is raised unchanged, without the key. If you interrupt or time out a
        submit yourself, pass your own ``idempotency_key`` so you can resubmit.
        """
        wire = _wire_request(request)
        key = wire.idempotency_key
        assert key is not None
        try:
            response = self._client.with_options(timeout=SUBMIT_TIMEOUT).send(
                endpoints.submit_run(workspace=self._client.resolve_workspace(workspace), body=wire),
                retry=SUBMIT_RETRY,
            )
            return response.data()
        except NemoClientError as exc:
            raise TasksetRunSubmitError(exc, key) from exc

    def retrieve(self, run_id: str, *, workspace: str | None = None) -> TasksetRunStatus:
        """Get a run's status, with its progress."""
        request = endpoints.get_run(workspace=self._client.resolve_workspace(workspace), run_id=run_id)
        return self._client.send(request).data()

    def list(
        self,
        *,
        workspace: str | None = None,
        active: bool = False,
        mine: bool = False,
        page: int = 1,
        page_size: int = 100,
    ) -> Page[TasksetRunStatus]:
        """One newest-first page of a workspace's runs; ``active`` keeps accepted and running runs only."""
        request = endpoints.list_runs(
            workspace=self._client.resolve_workspace(workspace),
            query_params={"active": active, "mine": mine, "page": page, "page_size": page_size},
        )
        return self._client.send(request).data()

    def tasks(
        self,
        run_id: str,
        *,
        workspace: str | None = None,
        phase: MemberPhase | None = None,
        page: int = 1,
        page_size: int = 100,
    ) -> Page[TasksetRunTask]:
        """One task-index-ordered page of a run's ``/tasks`` rows, by member name (``task-<i>``)."""
        request = endpoints.list_run_tasks(
            workspace=self._client.resolve_workspace(workspace),
            run_id=run_id,
            query_params={"page": page, "page_size": page_size, "phase": phase},  # the client drops a None phase
        )
        return self._client.send(request).data()

    def iter_tasks(self, run: str | TasksetRunStatus, *, workspace: str | None = None) -> Iterator[NamedTask]:
        """Every task of the run in task-index order, with its name in the pinned taskset.

        ``run`` is a run ID, or a run you already fetched, so its rows match what you show from it.
        Fetches the run (unless given), the pinned taskset revision (once per resource) and every ``/tasks`` page. A task whose
        row the controller hasn't created yet has ``task=None``. If the taskset can't be read (403/404), each
        task falls back to its member name (``task-<i>``) and only existing rows are yielded.

        A recent snapshot: the run, the taskset and the rows are read at slightly different times, so a task's
        row can trail the run's phase by one controller pass.

        Every page is read before the first task is yielded, so a failed read raises before any task.
        """
        yield from self._iter_tasks(self.retrieve(run, workspace=workspace) if isinstance(run, str) else run)

    def results(self, run_id: str, *, workspace: str | None = None) -> TasksetRunResults:
        """The run, each task with its result record, and the run's merged record once it's ready.

        Makes one result lookup per completed task, sequentially. The first failed lookup is raised and nothing
        partial is returned; the client's retry policy is what absorbs transient errors.
        """
        run = self.retrieve(run_id, workspace=workspace)
        tasks: builtins.list[TaskResult] = []
        for named in self._iter_tasks(run):
            result = None
            # Result records carry the Job's name as job_id (NEMO_JOB_ID), not its platform id.
            if (job := _completed_job(named)) is not None:
                found = self._results.list(workspace=run.workspace, job_id=job, page_size=1).data
                result = found[0] if found else None
            tasks.append(_with_result(named, result))
        record = self._results.retrieve(run.run_id, workspace=run.workspace) if run.result_state == "ready" else None
        return TasksetRunResults(run=run, tasks=tasks, result=record)

    def cancel(self, run_id: str, *, workspace: str | None = None) -> TasksetRunStatus:
        """Request a run's cancel; the run controller acts on it. A repeat keeps the first request's time."""
        request = endpoints.cancel_run(workspace=self._client.resolve_workspace(workspace), run_id=run_id)
        return self._client.send(request).data()

    def _iter_tasks(self, run: TasksetRunStatus) -> builtins.list[NamedTask]:
        """Every task of ``run``, read in full before any is returned.

        A list, not a generator, on purpose:

        - All or an error: ``iter_tasks`` and ``results`` never hand out tasks and then fail on a later page.
        - ``task=None`` entries need every page: a taskset index without a row is only known once all rows are.
        - Each call is one short read; a lazy generator would hold later pages open while the caller works.

        A run has at most a few hundred tasks. ``iter_tasks`` is already an iterator, so this can stream pages
        later without changing callers.
        """
        names = _names_by_index(self._pinned_taskset(run))
        rows: builtins.list[TasksetRunTask] = []
        number = 1
        while True:
            page = self.tasks(run.run_id, workspace=run.workspace, page=number, page_size=_TASKS_PAGE_SIZE)
            rows += page.data
            if _last_page(page, number):
                break
            number += 1
        return _named_tasks(names, rows)

    def _pinned_taskset(self, run: TasksetRunStatus) -> Taskset | None:
        """The run's pinned taskset revision; None when the caller can't read it. Only successes are cached."""
        key = _split_ref(run.taskset_ref)
        if key in self._taskset_cache:
            return self._taskset_cache[key]
        workspace, name, digest = key
        try:
            taskset = self._tasksets.retrieve(name, revision=digest or None, workspace=workspace)
        except (PermissionDeniedError, NotFoundError):
            return None
        _remember(self._taskset_cache, key, taskset)
        return taskset


class AsyncEvaluatorTasksetRunsResource:
    """Async resource mounted as ``AsyncEvaluator.taskset_runs``.

    Retries: ``submit`` always uses its own :data:`SUBMIT_RETRY` (no resend after the body was sent; the
    server's ``x-should-retry`` decides). Every other method follows the client's retry policy.
    """

    def __init__(self, client: AsyncEvaluatorClient) -> None:
        self._client = client
        self._tasksets = AsyncEvaluatorTasksetsResource(client)
        self._results = AsyncEvaluatorAgentEvalResultsResource(client)
        self._taskset_cache: dict[_TasksetKey, Taskset] = {}

    async def submit(self, request: TasksetRunInput, *, workspace: str | None = None) -> TasksetRunSubmitResponse:
        """Submit a run; a resubmit with the same ``idempotency_key`` returns the same run.

        Raises ``TasksetRunSubmitError`` for every failure. It carries ``idempotency_key`` (generated here if the
        request had none) and ``status_code`` (the error status; None for a transport failure or an unparseable
        2xx), with the typed client error as ``__cause__``.

        Cancellation (``asyncio.CancelledError``) is raised unchanged, without the key. If you cancel or time out
        a submit yourself, pass your own ``idempotency_key`` so you can resubmit.
        """
        wire = _wire_request(request)
        key = wire.idempotency_key
        assert key is not None
        try:
            response = await self._client.with_options(timeout=SUBMIT_TIMEOUT).send(
                endpoints.submit_run(workspace=self._client.resolve_workspace(workspace), body=wire),
                retry=SUBMIT_RETRY,
            )
            return response.data()
        except NemoClientError as exc:
            raise TasksetRunSubmitError(exc, key) from exc

    async def retrieve(self, run_id: str, *, workspace: str | None = None) -> TasksetRunStatus:
        """Get a run's status, with its progress."""
        request = endpoints.get_run(workspace=self._client.resolve_workspace(workspace), run_id=run_id)
        return (await self._client.send(request)).data()

    async def list(
        self,
        *,
        workspace: str | None = None,
        active: bool = False,
        mine: bool = False,
        page: int = 1,
        page_size: int = 100,
    ) -> Page[TasksetRunStatus]:
        """One newest-first page of a workspace's runs; ``active`` keeps accepted and running runs only."""
        request = endpoints.list_runs(
            workspace=self._client.resolve_workspace(workspace),
            query_params={"active": active, "mine": mine, "page": page, "page_size": page_size},
        )
        return (await self._client.send(request)).data()

    async def tasks(
        self,
        run_id: str,
        *,
        workspace: str | None = None,
        phase: MemberPhase | None = None,
        page: int = 1,
        page_size: int = 100,
    ) -> Page[TasksetRunTask]:
        """One task-index-ordered page of a run's ``/tasks`` rows, by member name (``task-<i>``)."""
        request = endpoints.list_run_tasks(
            workspace=self._client.resolve_workspace(workspace),
            run_id=run_id,
            query_params={"page": page, "page_size": page_size, "phase": phase},  # the client drops a None phase
        )
        return (await self._client.send(request)).data()

    async def iter_tasks(
        self, run: str | TasksetRunStatus, *, workspace: str | None = None
    ) -> AsyncIterator[NamedTask]:
        """Every task of the run in task-index order, with its name in the pinned taskset.

        ``run`` is a run ID, or a run you already fetched, so its rows match what you show from it.
        Fetches the run (unless given), the pinned taskset revision (once per resource) and every ``/tasks`` page. A task whose
        row the controller hasn't created yet has ``task=None``. If the taskset can't be read (403/404), each
        task falls back to its member name (``task-<i>``) and only existing rows are yielded.

        A recent snapshot: the run, the taskset and the rows are read at slightly different times, so a task's
        row can trail the run's phase by one controller pass.

        Every page is read before the first task is yielded, so a failed read raises before any task.
        """
        fetched = await self.retrieve(run, workspace=workspace) if isinstance(run, str) else run
        for named in await self._iter_tasks(fetched):
            yield named

    async def results(self, run_id: str, *, workspace: str | None = None) -> TasksetRunResults:
        """The run, each task with its result record, and the run's merged record once it's ready.

        Makes one result lookup per completed task, sequentially. The first failed lookup is raised and nothing
        partial is returned; the client's retry policy is what absorbs transient errors.
        """
        run = await self.retrieve(run_id, workspace=workspace)
        tasks: builtins.list[TaskResult] = []
        for named in await self._iter_tasks(run):
            result = None
            # Result records carry the Job's name as job_id (NEMO_JOB_ID), not its platform id.
            if (job := _completed_job(named)) is not None:
                found = (await self._results.list(workspace=run.workspace, job_id=job, page_size=1)).data
                result = found[0] if found else None
            tasks.append(_with_result(named, result))
        record = (
            await self._results.retrieve(run.run_id, workspace=run.workspace) if run.result_state == "ready" else None
        )
        return TasksetRunResults(run=run, tasks=tasks, result=record)

    async def cancel(self, run_id: str, *, workspace: str | None = None) -> TasksetRunStatus:
        """Request a run's cancel; the run controller acts on it. A repeat keeps the first request's time."""
        request = endpoints.cancel_run(workspace=self._client.resolve_workspace(workspace), run_id=run_id)
        return (await self._client.send(request)).data()

    async def _iter_tasks(self, run: TasksetRunStatus) -> builtins.list[NamedTask]:
        """Every task of ``run``, read in full before any is returned; see the sync resource's ``_iter_tasks``."""
        names = _names_by_index(await self._pinned_taskset(run))
        rows: builtins.list[TasksetRunTask] = []
        number = 1
        while True:
            page = await self.tasks(run.run_id, workspace=run.workspace, page=number, page_size=_TASKS_PAGE_SIZE)
            rows += page.data
            if _last_page(page, number):
                break
            number += 1
        return _named_tasks(names, rows)

    async def _pinned_taskset(self, run: TasksetRunStatus) -> Taskset | None:
        """The run's pinned taskset revision; None when the caller can't read it. Only successes are cached."""
        key = _split_ref(run.taskset_ref)
        if key in self._taskset_cache:
            return self._taskset_cache[key]
        workspace, name, digest = key
        try:
            taskset = await self._tasksets.retrieve(name, revision=digest or None, workspace=workspace)
        except (PermissionDeniedError, NotFoundError):
            return None
        _remember(self._taskset_cache, key, taskset)
        return taskset
