"""
Generate the OpenSandbox compose services extension ConfigMap from its source files.

The extension is four Python files that the stock OpenSandbox server loads from a ConfigMap. Three
sources stay in the scaled-evals plugin; the fourth is part of the shared nhx-sandbox package. The chart
ships a generated copy, with no namespace, at k8s/helm/files/opensandbox-ext/configmap.yaml, and
renders it into the OpenSandbox server's namespace.

To move the plugin directory, change PLUGIN_DIR.

Usage (run from the repository root):

  uv run python script/generate_opensandbox_ext_configmap.py          # write the ConfigMap
  uv run python script/generate_opensandbox_ext_configmap.py --check  # fail if it is out of date
"""

import argparse
import sys
from pathlib import Path

import yaml

# The repository root, so the script works from any directory.
REPO_ROOT = Path(__file__).resolve().parent.parent

# Where the extension's source files live. This is the one place to change when the plugin moves.
PLUGIN_DIR = REPO_ROOT / "plugins" / "_temporary-scaled-evals"
SANDBOX_PACKAGE_DIR = REPO_ROOT / "packages" / "nhx_sandbox" / "src" / "nhx_sandbox"

# The ConfigMap the chart ships: its name, the generated file, and the example server values that mount it.
CONFIGMAP_NAME = "nemo-opensandbox-ext"
CONFIGMAP_PATH = REPO_ROOT / "k8s" / "helm" / "files" / "opensandbox-ext" / "configmap.yaml"
SERVER_VALUES_PATH = REPO_ROOT / "k8s" / "helm" / "examples" / "opensandbox" / "opensandbox-server.yaml"

# ConfigMap key -> source file. The keys are what the server values' `items` list names.
SOURCES: dict[str, Path] = {
    "sitecustomize.py": PLUGIN_DIR / "opensandbox_ext" / "sitecustomize.py",
    "nemo_ext_server.py": PLUGIN_DIR / "opensandbox_ext" / "nemo_ext_server.py",
    "nemo_ext_pod.py": PLUGIN_DIR / "opensandbox_ext" / "nemo_ext_pod.py",
    "harbor_opensandbox_services.py": SANDBOX_PACKAGE_DIR / "harbor_opensandbox_services.py",
}

HEADER = f"""\
# GENERATED by script/generate_opensandbox_ext_configmap.py.
#
# The OpenSandbox compose services extension. The chart renders this into the OpenSandbox server's
# namespace when opensandbox.composeServices.enabled is true. Without Helm, apply it yourself:
#   kubectl apply -n <opensandbox namespace> -f configmap.yaml
# The server reads it only at start, so restart the server after any change.
apiVersion: v1
kind: ConfigMap
metadata:
  name: {CONFIGMAP_NAME}
data:
"""


def render() -> str:
    """Return the ConfigMap manifest, with each source as a literal block."""
    out = [HEADER]

    for key, source in SOURCES.items():
        text = source.read_text()
        lines = text.split("\n")

        # A literal block can't start with whitespace (YAML would need an indentation indicator), or hold these characters.
        if not text.strip() or lines[0][:1] in (" ", "\t"):
            raise SystemExit(f"{source}: must not be empty or start with whitespace")
        if "\t" in text or "\r" in text:
            raise SystemExit(f"{source}: tabs and carriage returns can't be written as a literal block")

        # Pick the block style that keeps the file's trailing newlines byte-identical:
        # `|` clips to one, `|+` keeps all of them, and `|-` is for a file with none.
        indicator = "|" if text.endswith("\n") else "|-"
        if text.endswith("\n\n"):
            indicator = "|+"

        # `|` and `|+` end the block with a line break that the writer below adds, so drop one from `body`.
        body = text[:-1] if text.endswith("\n") else text

        # One key per file, then its text indented under it. An empty line stays empty, with no trailing spaces.
        out.append(f"  {key}: {indicator}\n")
        out.extend(f"    {line}\n" if line else "\n" for line in body.split("\n"))

    return "".join(out)


def check_roundtrip(manifest: str) -> None:
    """Fail unless parsing the manifest gives back each source file byte for byte."""
    # Parse the manifest the way Kubernetes will, and compare the result with the sources.
    data = yaml.safe_load(manifest)["data"]

    # The same keys, in the same order.
    if list(data) != list(SOURCES):
        raise SystemExit(f"keys differ: {list(data)} != {list(SOURCES)}")

    # The same text for every key.
    for key, source in SOURCES.items():
        if data[key] != source.read_text():
            raise SystemExit(f"{key}: the manifest does not round-trip to {source}")


def check_server_values() -> None:
    """Fail unless the example server values mount exactly these keys."""
    # Find the volume that mounts our ConfigMap in the example server values, and read the keys it lists.
    server = yaml.safe_load(SERVER_VALUES_PATH.read_text())
    volumes = server["server"]["volumes"]
    items = next(v for v in volumes if v["name"] == CONFIGMAP_NAME)["configMap"]["items"]

    # The server only loads keys that are listed there, so a mismatch means a file that never reaches the server.
    if [item["key"] for item in items] != list(SOURCES):
        raise SystemExit(f"{SERVER_VALUES_PATH} mounts {[i['key'] for i in items]}, not {list(SOURCES)}")


def main() -> int:
    """Write the ConfigMap, or with --check fail if the committed copy is out of date."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the committed ConfigMap is out of date")
    args = parser.parse_args()

    # Build the manifest, and fail before writing anything if it is wrong.
    manifest = render()
    check_roundtrip(manifest)
    check_server_values()

    # --check: compare with the committed file and write nothing. CI runs this.
    if args.check:
        if not CONFIGMAP_PATH.exists() or CONFIGMAP_PATH.read_text() != manifest:
            print(
                f"{CONFIGMAP_PATH.relative_to(REPO_ROOT)} is out of date. "
                "Run 'uv run python script/generate_opensandbox_ext_configmap.py' and commit it.",
                file=sys.stderr,
            )
            return 1
        return 0

    # Otherwise write the file.
    CONFIGMAP_PATH.parent.mkdir(parents=True, exist_ok=True)
    CONFIGMAP_PATH.write_text(manifest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
