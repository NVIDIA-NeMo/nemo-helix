"""Build docs/tutorial.html from docs/tutorial.md.

The site in docs/ is plain HTML: docs/index.html is written by hand and
docs/tutorial.html is generated by this script, so it works on GitHub Pages,
any static host or opened straight from a clone. Rerun after editing
docs/tutorial.md:

    python scripts/build_site.py

Needs pandoc (https://pandoc.org/installing.html).
"""

import html
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "tutorial.md"
TEMPLATE = ROOT / "scripts" / "site-template.html"
OUTPUT = ROOT / "docs" / "tutorial.html"
DESCRIPTION = "Every step of the tutorial in full: train a small open model to take over a decision inside your agent with NeMo Helix."


def main() -> None:
    markdown = SOURCE.read_text()
    title = re.search(r"^# (.+)$", markdown, re.M).group(1)
    body = subprocess.run(
        ["pandoc", "--from", "gfm", "--to", "html"],
        input=markdown, capture_output=True, text=True, check=True,
    ).stdout
    page = TEMPLATE.read_text()
    page = page.replace("__TITLE__", html.escape(title))
    page = page.replace("__DESCRIPTION__", html.escape(DESCRIPTION))
    page = page.replace("__CONTENT__", body)
    OUTPUT.write_text(page)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
