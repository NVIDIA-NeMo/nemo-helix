import {
  SAFE_SYNTHESIZER_REPORT_DATA_URL,
  safeSynthesizerHandlers,
} from '@studio/mocks/handlers/safeSynthesizer';
import { server } from '@studio/mocks/node';
// eslint-disable-next-line import/extensions -- library output kept as plain JSON so it can be regenerated as is
import timeSeriesReportDataFixture from '@studio/mocks/safe-synthesizer/evaluation-report-data-time-series.json';
// eslint-disable-next-line import/extensions -- library output kept as plain JSON so it can be regenerated as is
import reportDataFixture from '@studio/mocks/safe-synthesizer/evaluation-report-data.json';
import {
  type EvaluationReportData,
  evaluationReportDataSchema,
} from '@studio/routes/SafeSynthesizerJobReportRoute/reportDataTypes';
import { http, HttpResponse } from 'msw';

/** Report data generated by the library from a tabular dataset with text and PII columns. */
export const reportData: EvaluationReportData = evaluationReportDataSchema.parse(reportDataFixture);

/** Report data generated by the library from a grouped time series. */
export const timeSeriesReportData: EvaluationReportData = evaluationReportDataSchema.parse(
  timeSeriesReportDataFixture
);

/** A completed job with its summary, HTML report, and report data; opt-in since some suites mock the SDK module whole. */
export const mockSafeSynthesizerJob = () => server.use(...safeSynthesizerHandlers);

export const mockReportData = (data: Record<string, unknown>) =>
  server.use(http.get(SAFE_SYNTHESIZER_REPORT_DATA_URL, () => HttpResponse.json(data)));

export const mockReportDataMissing = () =>
  server.use(
    http.get(SAFE_SYNTHESIZER_REPORT_DATA_URL, () =>
      HttpResponse.json({ detail: 'Result not found' }, { status: 404 })
    )
  );
