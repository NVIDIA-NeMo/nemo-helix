import { z } from 'zod';

export const MAX_REPORT_BYTES = 10 * 1024 * 1024;
export const ARM_NAMES = ['baseline', 'with-skill'] as const;
export type ArmName = (typeof ARM_NAMES)[number];
const count = z.number().int().nonnegative().safe();
const number = z.number().finite();
const pin = z.string().regex(/^[\w.-]+\/[\w.-]+#[a-f0-9]{64}$/);
const image = z.string().regex(/^[^@\s]+@sha256:[a-f0-9]{64}$/);
const text = z.string().min(1);

const coverageSchema = z.object({ total: count, scored: count, failed: count, missing: count });
const diagnosticSchema = z
  .object({
    message: z.string(),
    severity: z.string().optional(),
    details: z.record(z.unknown()).nullish(),
  })
  .passthrough();
const outputSchema = z.object({ name: text, value: z.unknown() });
const metricResultSchema = z
  .object({
    outputs: z.array(outputSchema),
    diagnostics: z.array(diagnosticSchema).default([]),
  })
  .passthrough();
const aggregateSchema = z
  .object({
    name: text,
    mean: number.nullish(),
    min: number.nullish(),
    max: number.nullish(),
    value: number.nullish(),
    count: count.optional(),
    nan_count: count.default(0),
    score_type: z.string().optional(),
  })
  .passthrough();
const aggregatesSchema = z.array(aggregateSchema).superRefine((scores, context) => {
  if (new Set(scores.map((score) => score.name)).size !== scores.length) {
    context.addIssue({ code: 'custom', message: 'Metric names must be unique.' });
  }
});
const measurementsSchema = z
  .object({
    prompt_tokens: count.nullish(),
    completion_tokens: count.nullish(),
    cache_read_tokens: count.nullish(),
    total_tokens: count.nullish(),
  })
  .passthrough();
const trialScoreSchema = metricResultSchema.extend({
  task_id: text,
  trial_id: text,
  metric_type: text,
  status: z.string(),
});
const armSchema = z
  .object({
    run_id: text,
    job_name: text,
    reward: number.nullable(),
    agent_image_ref: image,
    verifier_image_ref: image.nullable(),
    bundle: text,
    skill_refs: z.array(pin).optional(),
    discovery: z.boolean().optional(),
    activation: z.boolean().nullish(),
    measurements: measurementsSchema.optional(),
    evidence_error: z.string().optional(),
    replay_error: z.string().optional(),
    scoring_job: z.object({ name: text, id: z.string().optional() }).optional(),
    replay: z
      .object({
        bundle: text,
        source: z.literal('run').optional(),
        summary: z
          .object({
            trial_count: count,
            error_count: count,
            scores: z.object({ scores: aggregatesSchema }),
            metric_coverage: z.record(z.record(coverageSchema)).default({}),
          })
          .passthrough(),
        scores: z.array(trialScoreSchema),
      })
      .passthrough()
      .optional(),
  })
  .passthrough();

const reportSchema = z
  .object({
    taskset_ref: pin,
    skill_ref: pin.optional(),
    workspace: text,
    context: text,
    synthetic_demo: z.boolean().optional(),
    judge_model_ref: z.string().optional(),
    scoring_taskset_ref: pin.optional(),
    skill_files_hash: z.string().optional(),
    package_metrics: z.record(metricResultSchema).optional(),
    arms: z.object({ baseline: armSchema, 'with-skill': armSchema }),
    error: z.string().optional(),
  })
  .passthrough()
  .refine((report) => !!report.skill_ref || !!report.arms['with-skill'].skill_refs?.length, {
    path: ['skill_ref'],
    message: 'A pinned variant skill is required.',
  });

export type MetricResult = z.infer<typeof metricResultSchema>;
export type ComparisonReport = z.infer<typeof reportSchema>;
export type ComparisonArm = ComparisonReport['arms'][ArmName];
export type MetricCoverage = z.infer<typeof coverageSchema>;
type Aggregate = z.infer<typeof aggregateSchema>;

export function parseReport(json: string): ComparisonReport {
  let raw: unknown;
  try {
    raw = JSON.parse(json, (_key, value: unknown) => {
      if (typeof value === 'number' && !Number.isFinite(value))
        throw new Error('Non-finite number');
      return value;
    });
  } catch {
    throw new Error('Choose a valid JSON report generated by harbor_evals_skill/score.py.');
  }
  const result = reportSchema.safeParse(raw);
  if (!result.success) {
    const issue = result.error.issues[0];
    throw new Error(
      `Invalid comparison report at ${issue.path.join('.') || 'root'}: ${issue.message}`
    );
  }
  return result.data;
}

export async function readReport(file: File): Promise<ComparisonReport> {
  if (file.size > MAX_REPORT_BYTES)
    throw new Error('The comparison report must be 10 MiB or smaller.');
  return parseReport(await file.text());
}

export function comparisonWarnings(report: ComparisonReport): string[] {
  const baseline = report.arms.baseline;
  const treatment = report.arms['with-skill'];
  const warnings: string[] = [];
  if (baseline.run_id === treatment.run_id || baseline.job_name === treatment.job_name) {
    warnings.push('The arms must identify distinct runs and task jobs.');
  }
  if (
    baseline.agent_image_ref !== treatment.agent_image_ref ||
    baseline.verifier_image_ref !== treatment.verifier_image_ref
  ) {
    warnings.push(
      'The arms used different images. Metric differences are not a controlled skill comparison.'
    );
  }
  const skills = [...(baseline.skill_refs ?? []), ...(treatment.skill_refs ?? [])];
  if (report.skill_ref) skills.push(report.skill_ref);
  if (
    !report.taskset_ref.startsWith(`${report.workspace}/`) ||
    skills.some((skill) => !skill.startsWith(`${report.workspace}/`))
  ) {
    warnings.push('The pinned resources do not belong to the reported workspace.');
  }
  if (baseline.discovery !== false || treatment.discovery !== true) {
    warnings.push(
      'Skill discovery has not been confirmed as absent in the control and present in the variant.'
    );
  }
  return warnings;
}

export interface MetricObservation {
  value: number | null;
  label?: string;
  range?: { min: number; max: number };
  coverage?: MetricCoverage;
  status: 'Measured' | 'Partial' | 'Unmeasured' | 'Unavailable';
}

function observation(arm: ComparisonArm, name: string): MetricObservation {
  const summary = arm.replay?.summary;
  const aggregate: Aggregate | undefined = summary?.scores.scores.find(
    (score) => score.name === name
  );
  const coverage = Object.entries(summary?.metric_coverage ?? {})
    .flatMap(([metric, outputs]) =>
      Object.entries(outputs).map(([output, value]) => ({ name: `${metric}.${output}`, value }))
    )
    .find((entry) => entry.name === name)?.value;
  const measured = (coverage?.scored ?? aggregate?.count ?? 0) > 0;
  const rawValue = aggregate?.score_type === 'scalar' ? aggregate.value : aggregate?.mean;
  const value = measured && typeof rawValue === 'number' ? rawValue : null;
  const label = name.endsWith('.label')
    ? [
        ...new Set(
          (arm.replay?.scores ?? [])
            .filter((score) => score.status === 'completed' || score.status === 'partial')
            .flatMap((score) =>
              score.outputs
                .filter((output) => `${score.metric_type}.${output.name}` === name)
                .map((output) => output.value)
            )
            .filter((output): output is string => typeof output === 'string')
        ),
      ].join(', ')
    : '';
  const partial =
    (!label && (aggregate?.nan_count ?? 0) > 0) ||
    (!!coverage &&
      (coverage.failed > 0 || coverage.missing > 0 || coverage.scored < coverage.total));
  const min = aggregate?.min;
  const max = aggregate?.max;
  const range =
    aggregate?.score_type !== 'scalar' &&
    (aggregate?.count ?? coverage?.scored ?? 0) > 1 &&
    value !== null &&
    min != null &&
    max != null &&
    min < max &&
    min <= value &&
    value <= max
      ? { min, max }
      : undefined;
  return {
    value,
    range,
    ...(label ? { label } : {}),
    coverage,
    status: !summary
      ? 'Unavailable'
      : value === null && !label
        ? 'Unmeasured'
        : partial
          ? 'Partial'
          : 'Measured',
  };
}

export interface ComparisonMetric {
  name: string;
  baseline: MetricObservation;
  treatment: MetricObservation;
  delta: number | null;
}

export function comparisonMetrics(report: ComparisonReport): ComparisonMetric[] {
  const names = new Set<string>();
  for (const arm of Object.values(report.arms)) {
    arm.replay?.summary.scores.scores.forEach((score) => names.add(score.name));
    Object.entries(arm.replay?.summary.metric_coverage ?? {}).forEach(([metric, outputs]) => {
      Object.keys(outputs).forEach((output) => names.add(`${metric}.${output}`));
    });
  }
  const comparable =
    comparisonWarnings(report).length === 0 &&
    !report.error &&
    Object.values(report.arms).every(
      (arm) => !arm.evidence_error && !arm.replay_error && arm.replay?.summary.error_count === 0
    );
  return [...names].sort().map((name) => {
    const baseline = observation(report.arms.baseline, name);
    const treatment = observation(report.arms['with-skill'], name);
    return {
      name,
      baseline,
      treatment,
      delta:
        comparable &&
        baseline.status === 'Measured' &&
        treatment.status === 'Measured' &&
        baseline.value !== null &&
        treatment.value !== null
          ? treatment.value - baseline.value
          : null,
    };
  });
}

export interface TokenUsage {
  prompt: number | null;
  cached: number | null;
  completion: number | null;
  total: number | null;
  uncached: number | null;
}

export function tokenUsage(arm: ComparisonArm): TokenUsage {
  const prompt = arm.measurements?.prompt_tokens ?? null;
  const completion = arm.measurements?.completion_tokens ?? null;
  const cacheRead = arm.measurements?.cache_read_tokens ?? null;
  const cached = cacheRead !== null && prompt !== null && cacheRead <= prompt ? cacheRead : null;
  const efficiency = arm.replay?.summary.scores.scores.find(
    (score) => score.name === 'token_efficiency.efficiency_tokens'
  );
  return {
    prompt,
    cached,
    completion,
    total: prompt !== null && completion !== null ? prompt + completion : null,
    uncached:
      prompt !== null && cached !== null && completion !== null
        ? prompt - cached + completion
        : efficiency && (efficiency.count ?? 0) > 0
          ? (efficiency.mean ?? null)
          : null,
  };
}
