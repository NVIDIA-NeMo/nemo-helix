import Ajv2020 from 'ajv/dist/2020';
import standaloneCode from 'ajv/dist/standalone';

/**
 * Build-time codegen for the Draft 2020-12 meta-schema validator.
 *
 * Ajv validates by generating JavaScript source and compiling it with
 * `new Function` (`ajv/dist/compile/index.js`). Studio is served under a CSP
 * whose `script-src` carries no `'unsafe-eval'` (see
 * `services/studio/src/nhx/studio/static_files.py`), so that call throws in a
 * deployed Studio and takes down whatever is rendering — the dataset schema
 * editor on the fileset Files tab, in the bug that prompted this.
 *
 * Nothing on this path is actually dynamic: the only schema ever compiled is
 * the fixed Draft 2020-12 meta-schema, and the user's dataset schema is the
 * *data* passed to it. So compile it once, here, and ship the result.
 *
 * Split from the CLI entry point so the drift test can regenerate and compare
 * without the write side effect.
 */

const META_SCHEMA_ID = 'https://json-schema.org/draft/2020-12/schema';

const OUT_DIR = 'src/utils/jsonSchema/generated';

export const JS_PATH = `${OUT_DIR}/metaSchemaValidator.js`;
export const DTS_PATH = `${OUT_DIR}/metaSchemaValidator.d.ts`;

// The generator owns the header so the pre-commit copyright hook is a no-op on
// the artifact and can't rewrite it out of byte-equality with a fresh run.
const LICENSE_BANNER =
  '// SPDX-FileCopyrightText: Copyright (c) 2025-2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n' +
  '// SPDX-License-Identifier: Apache-2.0';

const GENERATED_BANNER =
  '// Code generated by scripts/generate-meta-schema-validator.ts. DO NOT EDIT.\n' +
  '// Regenerate with: pnpm --filter @nemo/common gen:meta-schema-validator';

// `const funcN = require("ajv/dist/runtime/x").default;` — ajv hard-codes this
// CJS form onto each runtime helper (see `equal.code` in
// `ajv/dist/runtime/equal.js`) and emits it verbatim even under `code.esm`.
const RUNTIME_REQUIRE = /const (\w+) = require\("([^"]+)"\)\.default;/g;

/**
 * Rewrite ajv's hard-coded `require()` calls for its runtime helpers into ESM
 * imports, so the module loads in a browser without a CJS interop shim.
 */
function requiresToEsmImports(code: string): string {
  const imports: string[] = [];
  const body = code.replace(RUNTIME_REQUIRE, (_match, binding: string, specifier: string) => {
    // Keep the file extension ajv omits: bundlers resolve either way, but
    // node's ESM resolver rejects an extensionless specifier, and @nemo/common
    // is consumed from node as well as from Vite.
    const resolved = specifier.endsWith('.js') ? specifier : `${specifier}.js`;
    imports.push(`import ${binding} from '${resolved}';`);
    return '';
  });
  // A leftover `require(` means ajv emitted a shape this transform doesn't
  // know about. Fail the build rather than ship a module that throws on load.
  if (body.includes('require(')) {
    throw new Error(
      'generate-meta-schema-validator: unhandled require() in ajv standalone output. ' +
        'The transform needs updating for this ajv version.'
    );
  }
  // Imports hoist, so placing them after the "use strict" prologue ajv emits
  // is fine and keeps that prologue first.
  return body.replace('"use strict";', `"use strict";\n${imports.join('\n')}\n`);
}

/** Source text for both generated files. */
export function buildMetaSchemaValidatorSources(): { js: string; dts: string } {
  // These options must match what `validate.ts` relied on when it called
  // `ajv.validateSchema` directly: `allErrors` so the editor lists every
  // problem at once, `strict: false` so unknown keywords aren't fatal.
  const ajv = new Ajv2020({
    strict: false,
    allErrors: true,
    code: { source: true, esm: true },
  });

  const validate = ajv.getSchema(META_SCHEMA_ID);
  if (!validate) {
    throw new Error(`generate-meta-schema-validator: no meta-schema at ${META_SCHEMA_ID}`);
  }

  const js = [
    LICENSE_BANNER,
    GENERATED_BANNER,
    '',
    requiresToEsmImports(standaloneCode(ajv, validate)),
    '',
  ].join('\n');

  const dts = [
    LICENSE_BANNER,
    GENERATED_BANNER,
    '',
    '/** One ajv error entry, narrowed to the fields `validate.ts` formats. */',
    'export interface MetaSchemaValidationError {',
    '  instancePath?: string;',
    '  message?: string;',
    '}',
    '',
    'export interface MetaSchemaValidateFunction {',
    '  (data: unknown): boolean;',
    '  /** Populated on failure, null on success. Overwritten by each call. */',
    '  errors?: MetaSchemaValidationError[] | null;',
    '}',
    '',
    'export declare const validate: MetaSchemaValidateFunction;',
    'export default validate;',
    '',
  ].join('\n');

  return { js, dts };
}
